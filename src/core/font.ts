export const FONT_W = 5;
export const FONT_H = 7;

export interface TextMaskOptions {
  // Horizontal cell repeat per font pixel. 2 compensates for ~0.5 char aspect
  // so letters read square. Vertical repeat is scale/2 rounded up.
  scaleX?: number;
  scaleY?: number;
  tracking?: number; // blank font-pixel columns between glyphs (pre-scale)
}

export type Mask = boolean[][]; // [row][col]

// Render a line of text into a boolean pixel mask at cell resolution.
// Unknown characters render as '?'. Lowercase folds to uppercase.
export function textToMask(text: string, opts: TextMaskOptions = {}): Mask {
  const sx = Math.max(1, opts.scaleX ?? 2);
  const sy = Math.max(1, opts.scaleY ?? 1);
  const tracking = opts.tracking ?? 1;

  const chars = [...text].map((c) => GLYPHS[c] ?? GLYPHS[c.toUpperCase()] ?? GLYPHS['?']!);
  const pxW = chars.length === 0 ? 0 : chars.length * (FONT_W + tracking) - tracking;
  const rows = FONT_H * sy;
  const cols = pxW * sx;

  const mask: Mask = Array.from({ length: rows }, () => new Array<boolean>(cols).fill(false));
  let xOff = 0;
  for (const glyph of chars) {
    for (let gy = 0; gy < FONT_H; gy++) {
      const bits = glyph[gy]!;
      for (let gx = 0; gx < FONT_W; gx++) {
        if (!(bits & (1 << (FONT_W - 1 - gx)))) continue;
        for (let ry = 0; ry < sy; ry++) {
          for (let rx = 0; rx < sx; rx++) {
            mask[gy * sy + ry]![(xOff + gx) * sx + rx] = true;
          }
        }
      }
    }
    xOff += FONT_W + tracking;
  }
  return mask;
}

// Pad a mask with blank border cells (fire needs headroom, glow needs margins).
export function padMask(mask: Mask, top: number, right: number, bottom: number, left: number): Mask {
  const rows = mask.length;
  const cols = rows > 0 ? mask[0]!.length : 0;
  const out: Mask = Array.from({ length: rows + top + bottom }, () =>
    new Array<boolean>(cols + left + right).fill(false),
  );
  for (let y = 0; y < rows; y++) {
    for (let x = 0; x < cols; x++) {
      if (mask[y]![x]) out[y + top]![x + left] = true;
    }
  }
  return out;
}
